
const Order = require('../models/order.model');
const Product = require('../models/product.model');
const Farmer = require('../models/farmer.model');
const foodModel = require('../models/food.model')

// @desc    Create new order
// @route   POST /api/orders
// @access  Private/Consumer
exports.createOrder = async (req, res) => {
  console.log(req.body)
  try {
    const {
      items,
      shippingAddress,
      paymentMethod
    } = req.body;

    if (!items || items.length === 0) {
      return res.status(400).json({
        success: false,
        message: 'No order items'
      });
    }

    // Calculate prices and validate products
    const orderItems = [];
    let subTotal = 0;
    const farmerIds = new Set();

    for (const item of items) {
      const product = await foodModel.findById(item._id);

      if (!product) {
        return res.status(404).json({
          success: false,
          message: `Product not found with ID: ${item.product}`
        });
      }

      // Check if product is in stock
      if (!product.inStock) {
        return res.status(400).json({
          success: false,
          message: `Product ${product.name} is not in stock`
        });
      }

      // Check if quantity is available
      // if (item.quantity > product.quantity) {
      //   return res.status(400).json({
      //     success: false,
      //     message: `Insufficient quantity for ${product.name}`
      //   });
      // }

      // Calculate price
      console.log(item.quantity)
      const price = product.discountPrice || product.price;
      const total = price * item.quantity;

      // Add to order items
      orderItems.push({
        product: product._id,
        quantity: item.quantity,
        price,
        total
      });

      // Add to subtotal
      subTotal += total;

      // Track unique farmers
      farmerIds.add(product.farmer.toString());

      // Decrease product quantity
      await Product.findByIdAndUpdate(product._id, {
        $inc: { quantity: -item.quantity }
      });
    }

    // Calculate taxes and delivery fee (example rates)
    const taxRate = 0.05; // 5%
    const tax = subTotal * taxRate;

    // Delivery fee based on order value
    let deliveryFee = 0;
    if (subTotal < 500) {
      deliveryFee = 50;
    } else if (subTotal < 1000) {
      deliveryFee = 25;
    }

    // Calculate total
    const total = subTotal + tax + deliveryFee;

    // Create order
    const order = await Order.create({
      orderNumber: '', // Will be generated by pre-save hook
      consumer: "662df2e5f3f26c001ee5f59e",
      items: orderItems,
      farmers: Array.from(farmerIds),
      subTotal,
      tax,
      deliveryFee,
      total,
      shippingAddress,
      paymentMethod,
      paymentStatus: paymentMethod === 'cod' ? 'pending' : 'pending',
      estimatedDeliveryDate: new Date(Date.now() + 3 * 24 * 60 * 60 * 1000) // 3 days from now
    });

    res.status(201).json({
      success: true,
      data: order
    });
  } catch (error) {
    console.log(error)
    res.status(500).json({
      success: false,
      message: error.message || 'Server error'
    });
  }
};

// @desc    Get all orders
// @route   GET /api/orders
// @access  Private
exports.getOrders = async (req, res) => {
  try {
    const {
      status,
      fromDate,
      toDate,
      farmerId,
      page = 1,
      limit = 10
    } = req.query;

    // Build query based on user role
    const query = {};

    if (req.user.role === 'consumer') {
      // Consumers can only see their own orders
      query.consumer = req.user.id;
    } else if (req.user.role === 'farmer') {
      // Farmers can only see orders containing their products
      const farmer = await Farmer.findOne({ user: req.user.id });
      if (farmer) {
        query.farmers = farmer._id;
      } else {
        return res.status(404).json({
          success: false,
          message: 'Farmer profile not found'
        });
      }
    }

    // Filter by status
    if (status) {
      query.orderStatus = status;
    }

    // Filter by date range
    if (fromDate && toDate) {
      query.createdAt = {
        $gte: new Date(fromDate),
        $lte: new Date(toDate)
      };
    }

    // Filter by specific farmer (for admins)
    if (req.user.role === 'admin' && farmerId) {
      query.farmers = farmerId;
    }

    // Pagination
    const skip = (page - 1) * limit;

    const orders = await Order.find(query)
      .populate({
        path: 'consumer',
        select: 'name email phone'
      })
      .populate({
        path: 'items.product',
        select: 'name images category'
      })
      .skip(skip)
      .limit(parseInt(limit))
      .sort({ createdAt: -1 });

    const total = await Order.countDocuments(query);

    res.status(200).json({
      success: true,
      count: orders.length,
      pagination: {
        total,
        page: parseInt(page),
        limit: parseInt(limit),
        totalPages: Math.ceil(total / limit)
      },
      data: orders
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message || 'Server error'
    });
  }
};

// @desc    Get single order
// @route   GET /api/orders/:id
// @access  Private
exports.getOrder = async (req, res) => {
  try {
    const order = await Order.findById(req.params.id)
      .populate({
        path: 'consumer',
        select: 'name email phone'
      })
      .populate({
        path: 'items.product',
        select: 'name images category farmer',
        populate: {
          path: 'farmer',
          select: 'farmName user',
          populate: {
            path: 'user',
            select: 'name'
          }
        }
      });

    if (!order) {
      return res.status(404).json({
        success: false,
        message: 'Order not found'
      });
    }

    // Check if user is authorized to view this order
    if (req.user.role === 'consumer' && order.consumer._id.toString() !== req.user.id) {
      return res.status(403).json({
        success: false,
        message: 'Not authorized to view this order'
      });
    }

    if (req.user.role === 'farmer') {
      const farmer = await Farmer.findOne({ user: req.user.id });

      if (!farmer || !order.farmers.includes(farmer._id)) {
        return res.status(403).json({
          success: false,
          message: 'Not authorized to view this order'
        });
      }
    }

    res.status(200).json({
      success: true,
      data: order
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message || 'Server error'
    });
  }
};

// @desc    Update order status
// @route   PUT /api/orders/:id/status
// @access  Private/Admin-Farmer
exports.updateOrderStatus = async (req, res) => {
  try {
    const { orderStatus } = req.body;

    // Validate order status
    const validStatuses = ['placed', 'confirmed', 'processing', 'packed', 'shipped', 'delivered', 'cancelled', 'returned'];
    if (!validStatuses.includes(orderStatus)) {
      return res.status(400).json({
        success: false,
        message: 'Invalid order status'
      });
    }

    const order = await Order.findById(req.params.id);

    if (!order) {
      return res.status(404).json({
        success: false,
        message: 'Order not found'
      });
    }

    // Check if user is authorized to update this order
    if (req.user.role === 'farmer') {
      const farmer = await Farmer.findOne({ user: req.user.id });

      if (!farmer || !order.farmers.includes(farmer._id)) {
        return res.status(403).json({
          success: false,
          message: 'Not authorized to update this order'
        });
      }
    }

    // Update order status
    order.orderStatus = orderStatus;

    // If order is delivered, set actual delivery date
    if (orderStatus === 'delivered') {
      order.actualDeliveryDate = new Date();
    }

    // If order is cancelled and was previously confirmed, restore product quantities
    if (orderStatus === 'cancelled' && order.orderStatus !== 'cancelled') {
      for (const item of order.items) {
        await Product.findByIdAndUpdate(item.product, {
          $inc: { quantity: item.quantity }
        });
      }
    }

    await order.save();

    res.status(200).json({
      success: true,
      data: order
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message || 'Server error'
    });
  }
};
